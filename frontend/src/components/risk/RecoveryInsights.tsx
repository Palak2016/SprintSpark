const DAY_W = 14;

export const ScheduleComparisonView: React.FC<{ comparison: Partial<ScheduleComparison> }> = ({ comparison }) => {
  const rows = useMemo(
    () =>
      compareScheduleRows(
        comparison.before?.tasks ?? [],
        comparison.after?.tasks ?? [],
        comparison.changed_task_ids ?? []
      ),
    [comparison]
  );

  if (!comparison.before || rows.length === 0) {
    return <p className="text-xs text-[#A99DBD]">No schedule comparison was recorded for this proposal.</p>;
  }

  const days = rows.flatMap((r) => [r.before.start, r.before.due, r.before.finish, r.after.start, r.after.due, r.after.finish]).filter((d): d is number => d !== null);
  const target = toDay(comparison.target_end_date ?? null);
  const computed = toDay(comparison.computed_for ?? null);
  if (target !== null) days.push(target);
  if (computed !== null) days.push(computed);
  const start = Math.min(...days) - 1;
  const end = Math.max(...days) + 1;
  const width = (end - start + 1) * DAY_W;
  const x = (d: number) => (d - start) * DAY_W;
  const saved = comparison.business_days_saved;

  const bar = (s: number | null, e: number | null, y: number, color: string, opacity = 1) =>
    s !== null && e !== null ? (
      <rect x={x(s)} y={y} width={Math.max(DAY_W, (e - s + 1) * DAY_W)} height={8} rx={3} fill={color} opacity={opacity} />
    ) : null;

  const finishMarker = (d: number | null, y: number, late: boolean) =>
    d !== null ? (
      <path d={`M${x(d) + DAY_W / 2},${y} l5,5 l-5,5 l-5,-5 z`} fill={late ? CHART_COLORS.serious : '#FAF8FF'} stroke="#19112B" strokeWidth={1.5} />
    ) : null;

  const monthStarts: number[] = [];
  for (let d = start; d <= end; d++) if (new Date(d * 86_400_000).getUTCDate() === 1 || d === start) monthStarts.push(d);
  const mondays: number[] = [];
  for (let d = start; d <= end; d++) if (new Date(d * 86_400_000).getUTCDay() === 1) mondays.push(d);

  return (
    <div className="space-y-4">
      <div className="grid grid-cols-1 gap-3 sm:grid-cols-3">
        <div className="rounded-xl border border-white/[0.07] bg-[#130D21] p-3">
          <p className="text-[10px] text-[#A99DBD]">Projected completion now</p>
          <p className="mt-1 text-sm font-semibold text-white">{formatIndianDate(comparison.before?.projected_completion)}</p>
        </div>
        <div className="rounded-xl border border-violet-400/20 bg-violet-500/[0.06] p-3">
          <p className="text-[10px] text-violet-200">Projected with this proposal</p>
          <p className="mt-1 text-sm font-semibold text-white">{formatIndianDate(comparison.after?.projected_completion)}</p>
        </div>
        <div className="rounded-xl border border-white/[0.07] bg-[#130D21] p-3">
          <p className="text-[10px] text-[#A99DBD]">Estimated change</p>
          <p className="mt-1 text-sm font-semibold text-white">
            {saved == null
              ? 'Not available'
              : saved > 0
                ? `${saved} working day${saved === 1 ? '' : 's'} earlier`
                : saved < 0
                  ? `${-saved} working day${saved === -1 ? '' : 's'} later`
                  : 'No change to the finish date'}
          </p>
        </div>
      </div>

      <p className="text-[11px] leading-5 text-amber-200/90">
        {comparison.label ?? 'Projection, not a measured result.'} Computed for {formatIndianDate(comparison.computed_for)}.
      </p>

      <div className="overflow-x-auto rounded-xl border border-white/[0.07] bg-[#130D21]">
        <div className="flex min-w-max">
          <div className="sticky left-0 z-10 w-48 shrink-0 border-r border-white/[0.06] bg-[#130D21]">
            <div className="h-8 border-b border-white/[0.06] px-3 pt-2 text-[10px] text-[#A99DBD]">Task</div>
            {rows.map((r) => (
              <div key={r.taskId} className="flex h-12 flex-col justify-center border-b border-white/[0.04] px-3">
                <span className={`truncate text-[11px] ${r.changed ? 'font-semibold text-white' : 'text-[#D8CFE7]'}`} title={r.title}>
                  {r.changed && <span className="mr-1 text-violet-300">●</span>}
                  {r.title}
                </span>
                <span className="truncate text-[10px] text-[#8f84a3]">
                  {r.assigneeBefore ?? 'Unassigned'}
                  {r.assigneeAfter !== r.assigneeBefore && <span className="text-violet-200"> → {r.assigneeAfter ?? 'Unassigned'}</span>}
                </span>
              </div>
            ))}
          </div>
          <svg width={width} height={32 + rows.length * 48} role="img" aria-label="Current and proposed schedule for each task">
            {mondays.map((d) => (
              <line key={`g${d}`} x1={x(d)} x2={x(d)} y1={32} y2={32 + rows.length * 48} stroke="rgba(255,255,255,0.05)" />
            ))}
            {monthStarts.map((d) => (
              <text key={`m${d}`} x={x(d) + 2} y={13} fontSize="10" fill="#D8CFE7">{formatDayLabel(d, { month: 'short', year: '2-digit' })}</text>
            ))}
            {mondays.map((d) => (
              <text key={`t${d}`} x={x(d) + 2} y={26} fontSize="9" fill="#8f84a3">{formatDayLabel(d, { day: 'numeric' })}</text>
            ))}
            <line x1={0} x2={width} y1={31.5} y2={31.5} stroke="rgba(255,255,255,0.08)" />
            {rows.map((r, i) => {
              const y = 32 + i * 48;
              return (
                <g key={r.taskId}>
                  <title>
                    {`${r.title}\nNow: ${formatIndianDate(r.before.start !== null ? new Date(r.before.start * 86_400_000).toISOString().slice(0, 10) : null)} to ${formatIndianDate(
                      r.before.due !== null ? new Date(r.before.due * 86_400_000).toISOString().slice(0, 10) : null
                    )}${r.dueShiftDays ? `\nProposed due date moves ${r.dueShiftDays > 0 ? '+' : ''}${r.dueShiftDays} day(s)` : ''}${
                      r.finishShiftDays ? `\nProjected finish moves ${r.finishShiftDays > 0 ? '+' : ''}${r.finishShiftDays} day(s)` : ''
                    }`}
                  </title>
                  <line x1={0} x2={width} y1={y + 47.5} y2={y + 47.5} stroke="rgba(255,255,255,0.04)" />
                  {bar(r.before.start, r.before.due, y + 10, CHART_COLORS.neutral, 0.55)}
                  {finishMarker(r.before.finish, y + 9, r.before.late)}
                  {bar(r.after.start, r.after.due, y + 27, r.changed ? '#a78bfa' : CHART_COLORS.neutral, r.changed ? 1 : 0.3)}
                  {finishMarker(r.after.finish, y + 26, r.after.late)}
                </g>
              );
            })}
            {computed !== null && (
              <line x1={x(computed) + DAY_W / 2} x2={x(computed) + DAY_W / 2} y1={32} y2={32 + rows.length * 48} stroke={CHART_COLORS.today} strokeWidth={1.5} />
            )}
            {target !== null && (
              <line x1={x(target) + DAY_W} x2={x(target) + DAY_W} y1={32} y2={32 + rows.length * 48} stroke={CHART_COLORS.warning} strokeWidth={1.5} strokeDasharray="4 4" />
            )}
          </svg>
        </div>
      </div>

      <div className="flex flex-wrap gap-x-5 gap-y-2 text-[11px] text-[#B7ADC9]">
        <span className="inline-flex items-center gap-1.5"><span className="inline-block h-2 w-4 rounded-sm" style={{ background: CHART_COLORS.neutral, opacity: 0.55 }} /> Current plan (start to due)</span>
        <span className="inline-flex items-center gap-1.5"><span className="inline-block h-2 w-4 rounded-sm bg-[#a78bfa]" /> Proposed plan for a changed task</span>
        <span className="inline-flex items-center gap-1.5"><svg width="10" height="10" aria-hidden="true"><path d="M5,0 l5,5 l-5,5 l-5,-5 z" fill="#FAF8FF" /></svg> Projected finish</span>
        <span className="inline-flex items-center gap-1.5"><svg width="10" height="10" aria-hidden="true"><path d="M5,0 l5,5 l-5,5 l-5,-5 z" fill={CHART_COLORS.serious} /></svg> Projected finish after due date</span>
        <span className="inline-flex items-center gap-1.5"><span className="inline-block h-3 w-[2px] bg-[#c4b5fd]" /> Today</span>
        {target !== null && <span className="inline-flex items-center gap-1.5"><span className="inline-block h-3 w-0 border-l-2 border-dashed border-[#fab219]" /> Project target</span>}
      </div>

      {(comparison.dependency_conflicts_before?.length ?? 0) > 0 && (
        <div className="rounded-xl border border-rose-400/20 bg-rose-500/[0.06] p-3 text-xs text-rose-100">
          <p className="font-semibold">Dependency conflicts in the current plan</p>
          <ul className="mt-1 list-disc space-y-0.5 pl-4">
            {comparison.dependency_conflicts_before!.map((c) => (
              <li key={`${c.task_id}-${c.prerequisite_id}`}>
                Task #{c.task_id} is due {formatIndianDate(c.task_due)}, but its prerequisite #{c.prerequisite_id} is due {formatIndianDate(c.prerequisite_due)}.
              </li>
            ))}
          </ul>
          <p className="mt-1 text-rose-200/80">Every proposed date change was checked so it does not create new conflicts.</p>
        </div>
      )}

      {(comparison.workload_before?.length ?? 0) > 0 && (
        <div>
          <h4 className="mb-3 text-xs font-semibold text-white">Workload before and after (until the target date)</h4>
          <CapacityBars
            unit="h"
            valueLabel="Remaining effort with this proposal"
            capacityLabel="Available hours"
            compareLabel="Remaining effort now"
            rows={(comparison.workload_after ?? []).map((after) => {
              const before = comparison.workload_before!.find((b) => b.user_id === after.user_id);
              return {
                key: String(after.user_id ?? 'unassigned'),
                label: after.name,
                value: after.remaining_hours,
                compareValue: before?.remaining_hours ?? 0,
                capacity: after.user_id === null ? null : after.capacity_hours,
                over: after.over_capacity,
              };
            })}
          />
        </div>
      )}

      <details className="text-[11px] leading-5 text-[#A99DBD]">
        <summary className="cursor-pointer text-[#D8CFE7]">How the projection is calculated</summary>
        <p className="mt-2">{comparison.method}</p>
        <ul className="mt-2 list-disc space-y-1 pl-4">
          {(comparison.assumptions ?? []).map((a) => <li key={a}>{a}</li>)}
        </ul>
        <p className="mt-2">Escalations and advisory actions do not change the projection, because their effect on time cannot be measured from project data.</p>
      </details>
    </div>
  );
};

