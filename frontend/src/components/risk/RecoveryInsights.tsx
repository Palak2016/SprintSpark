export const ValidationPanel: React.FC<{ trace: GenerationTrace }> = ({ trace }) => {
  const v = trace.validation ?? {};
  const rejected = trace.rejected_actions ?? [];
  const warnings = v.warnings ?? [];
  if (!v.status) return null;
  return (
    <div className="space-y-2 text-xs">
      <p className="flex items-center gap-1.5 font-semibold text-white">
        {v.status === 'PASSED' ? <CheckCircle2 className="h-4 w-4 text-[#0ca30c]" /> : <ShieldAlert className="h-4 w-4 text-[#fab219]" />}
        {v.status === 'PASSED'
          ? 'All proposed actions passed validation against project data.'
          : v.status === 'PASSED_WITH_WARNINGS'
            ? 'Proposed actions are valid, with warnings to review.'
            : 'Some suggested actions were rejected and are not part of this proposal.'}
      </p>
      {warnings.length > 0 && (
        <ul className="space-y-1">
          {warnings.map((w) => (
            <li key={w} className="flex items-start gap-1.5 text-amber-100/90">
              <AlertTriangle className="mt-0.5 h-3.5 w-3.5 shrink-0 text-[#fab219]" /> {w}
            </li>
          ))}
        </ul>
      )}
      {rejected.length > 0 && (
        <details>
          <summary className="cursor-pointer text-[#D8CFE7]">{rejected.length} rejected suggestion(s)</summary>
          <ul className="mt-2 space-y-1">
            {rejected.map((r, i) => (
              <li key={i} className="flex items-start gap-1.5 text-rose-100/90">
                <XCircle className="mt-0.5 h-3.5 w-3.5 shrink-0 text-[#d03b3b]" />
                <span>
                  {r.source === 'AI' ? 'AI' : 'Rule'} {r.action_type.replace(/_/g, ' ').toLowerCase()} on task #{r.task_id}: {r.errors.join(' ')}
                </span>
              </li>
            ))}
          </ul>
        </details>
      )}
    </div>
  );
};

export const TraceDetails: React.FC<{ proposal: RecoveryProposal }> = ({ proposal }) => {
  const t = proposal.generation_trace;
  if (!t?.run_id) return null;
  const llm = t.llm;
  const rows: [string, React.ReactNode][] = [
    ['Run ID', <span className="font-mono">{t.run_id}</span>],
    ['Generated', formatIndianDateTime(t.completed_at ?? t.started_at ?? proposal.created_at)],
    ['Mode', describeProvenance(t).label],
    ['Language model called', llm?.invoked ? 'Yes' : 'No'],
    ['Model result', llm?.status ? llm.status.replace(/_/g, ' ').toLowerCase() : '—'],
    ['Provider / model', llm?.provider ? `${llm.provider} / ${llm.model ?? 'unknown'}` : '—'],
    ['Model latency', llm?.latency_ms != null ? `${(llm.latency_ms / 1000).toFixed(1)}s` : '—'],
    ['Workflow steps', (t.graph_nodes ?? []).join(' → ') || '—'],
  ];
  if (llm?.error) rows.push(['Model error', llm.error]);
  if (llm?.skip_reason) rows.push(['Why AI was not used', llm.skip_reason]);
  return (
    <details className="rounded-xl border border-white/[0.07] bg-[#130D21] p-3 text-xs">
      <summary className="flex cursor-pointer items-center gap-1.5 font-semibold text-[#D8CFE7]">
        <GitCompareArrows className="h-3.5 w-3.5" /> How this proposal was generated
      </summary>
      <dl className="mt-3 grid grid-cols-1 gap-x-4 gap-y-2 sm:grid-cols-[10rem_1fr]">
        {rows.map(([k, v]) => (
          <React.Fragment key={k}>
            <dt className="text-[#8f84a3]">{k}</dt>
            <dd className="break-words text-[#D8CFE7]">{v}</dd>
          </React.Fragment>
        ))}
      </dl>
    </details>
  );
};
