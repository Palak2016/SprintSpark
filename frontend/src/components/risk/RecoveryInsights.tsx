export const describeProvenance = (trace?: GenerationTrace | null) => {
  const llm = trace?.llm;
  const mode = trace?.generation_mode;
  if (!trace || !mode) {
    return {
      tone: 'unknown' as const,
      label: 'Source not recorded',
      detail: 'Created before generation tracing was added, so it is not known whether a model was used.',
    };
  }
  if (mode === 'AI_HYBRID') {
    return {
      tone: 'ai' as const,
      label: 'AI recommendation',
      detail: `Generated by ${llm?.provider ?? 'the configured'} model ${llm?.model ?? ''}, then checked against project data by WorkPilot's validator.`.replace('  ', ' '),
    };
  }
  if (mode === 'RULE_BASED') {
    return {
      tone: 'rule' as const,
      label: 'Rule-based (no AI needed)',
      detail: llm?.skip_reason ?? 'Recovery was not needed, so the language model was not called.',
    };
  }
  const reason =
    llm?.status === 'NOT_CONFIGURED'
      ? 'No language model is configured.'
      : llm?.status === 'FAILED'
        ? `The language model call failed (${llm.error ?? llm.error_category ?? 'error'}).`
        : trace.selection_reason ?? 'The AI suggestions did not pass validation.';
  return {
    tone: 'fallback' as const,
    label: 'Rule-based fallback',
    detail: `${reason} These actions come from WorkPilot's rule-based planner, not from AI.`,
  };
};

export const ProvenanceBadge: React.FC<{ trace?: GenerationTrace | null; compact?: boolean }> = ({ trace, compact }) => {
  const p = describeProvenance(trace);
  const styles = {
    ai: 'border-violet-400/30 bg-violet-500/10 text-violet-200',
    rule: 'border-white/10 bg-white/[0.04] text-[#D8CFE7]',
    fallback: 'border-amber-400/25 bg-amber-500/10 text-amber-200',
    unknown: 'border-white/10 bg-white/[0.03] text-[#A99DBD]',
  }[p.tone];
  const Icon = p.tone === 'ai' ? BrainCircuit : p.tone === 'unknown' ? CircleHelp : Cpu;
  return (
    <span className={`inline-flex items-center gap-1.5 rounded-md border px-2 py-1 text-[10px] font-semibold ${styles}`} title={p.detail}>
      <Icon className="h-3 w-3" />
      {p.label}
      {!compact && p.tone === 'ai' && trace?.llm?.model && <span className="font-normal opacity-80">({trace.llm.model})</span>}
    </span>
  );
};

